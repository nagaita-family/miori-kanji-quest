// Prevent iPad home-screen app from silently staying on an outdated shell.
const fs = require('node:fs');
const assert = require('node:assert/strict');
const read = path => fs.readFileSync(path, 'utf8');
const html = read('index.html');
const oldApp = read('app-v10.js');
const updater = read('pwa-update-v303.js');
const worker = read('sw.js');
const manifest = JSON.parse(read('manifest.webmanifest'));
const version = JSON.parse(read('app-version.json'));
assert.equal(version.build, '20261031.1');
assert.ok(updater.includes("const BUILD = '20261031.1'"));
assert.equal(manifest.id, './', 'Stable web-app identity preserves existing installations');
assert.equal(manifest.scope, './');
assert.equal(manifest.display, 'standalone');
assert.match(manifest.start_url, /index\.html\?entry=3031$/, 'New home-screen icons launch versioned HTML');
assert.match(html, /manifest\.webmanifest\?v=3031/);
assert.match(html, /app-v10\.js\?v=20261025-pwa303/);
assert.ok(html.includes('pwa-update-v303.js?v=20261031-p82'));
assert.match(html, /id="bestGalleryGlobalOpen"/, 'Saved-best gallery is available on every app screen');
assert.match(updater, /serviceWorker\.register/, 'Install network-first worker for future launches');
assert.match(updater, /app-version\.json/, 'Check a separately versioned freshness marker');
assert.match(updater, /cache: 'no-store'/);
assert.match(updater, /visibilitychange/, 'Check again when home-screen app comes to foreground');
assert.match(updater, /window\.location\.replace/, 'Reload an explicitly cache-busted HTML entry');
assert.match(updater, /sessionStorage/, 'Avoid endless refresh loops');
assert.match(updater, /canRefreshWithoutLosingInk/, 'Do not automatically discard active handwriting');
assert.doesNotMatch(updater, /localStorage\.(?:clear|removeItem|setItem)\s*\(/, 'Do not wipe learning records');
assert.doesNotMatch(oldApp, /getRegistrations\(\).*unregister\(/, 'Legacy JS must not disable the new worker');
assert.match(worker, /request\.mode !== 'navigate'/);
assert.match(worker, /cache: 'no-store'/);
assert.doesNotMatch(worker, /caches\.delete\(key\)/, 'Never delete arbitrary other family app caches');
console.log('PASS iPad PWA updates: network-first shell, version detection, safe refresh and stored-progress protection.');
