// node kanken9-v285-smoke-test.cjs — based on the supplied 2026 9級A sample format.
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const ctx={window:{},console};
for(const f of ['kanken9-data-v280.js','kanken9-exam-data-v283.js','kanken9-exam-finalize-v283.js','kanken9-quality-v285.js'])vm.runInNewContext(fs.readFileSync(f,'utf8'),ctx);
const D=ctx.window.MioriKankenPaperV283Data,B=ctx.window.MioriKanken9DataV280;
assert.equal(D.qualityVersion,'v285');
assert.equal(D.questions.length,105);assert.equal(D.questions.reduce((x,q)=>x+q.point,0),150);
assert.deepEqual(Array.from(D.sections.map(s=>D.groups[s.key].length)),[26,10,8,10,6,10,10,25]);
assert.ok(D.questions.every(q=>!!q.answer&&q.id&&q.point));
assert.ok(D.questions.every(q=>!q.target||[...q.target].every(c=>B.chars.includes(c))));
const reading=[...D.groups.I,...D.groups.IV];
assert.ok(reading.filter(q=>q.target.length>1).length>=8,'Include contextual compound on-readings');
assert.ok(reading.some(q=>q.target==='空'&&q.answer==='そら')&&reading.some(q=>q.target==='空'&&q.answer==='くう'),'Same kanji needs both kun and on in context');
assert.ok(reading.every(q=>q.text.includes(q.target)&&/^[ぁ-んー]+$/.test(q.answer)));
assert.ok(D.groups.II.filter(q=>B.G2.includes(q.target)).length>=7,'Stroke questions must not be limited to simplest Grade-1 glyphs');
assert.ok(D.groups.II.every(q=>q.strokes.length>=Number(q.answer)&&q.strokes.length>=5));
assert.ok(D.groups.VI.every(q=>q.kind==='family'&&!q.options&&q.text.includes(q.part)&&!q.text.includes(q.answer)),'Section VI: shared parts, NEVER a word bank that gives away the answer');
assert.deepEqual(Array.from(new Set(D.groups.VI.map(q=>q.part))).sort(),['囗','弓','言','辶','雨'].sort());
assert.ok(D.groups.VII.every(q=>q.kind==='relation'),'Section VII includes related pairs, not only antonyms');
assert.equal(new Set(D.groups.VIII.map(q=>q.target)).size,25);
assert.ok(D.groups.VIII.every(q=>!q.text.includes(q.answer)),'Write prompts cannot reveal their answers');
const css=fs.readFileSync('kanken9-paper-layout-v285.css','utf8');
assert.ok(css.includes('writing-mode:vertical-rl')&&css.includes('white-space:nowrap'),'Paper questions must stay vertical and not break');
assert.ok(css.includes('grid-template-columns:minmax(0,1fr) minmax(0,1fr)'),'Question and answer must occupy one shared paper area');
assert.ok(css.includes('.k9ExamClear')&&css.includes('.k9DailyErase'),'Accessible eraser controls retained');
const loader=fs.readFileSync('app-v240-release.js','utf8'),html=fs.readFileSync('index.html','utf8');
assert.ok(loader.indexOf('kanken9-quality-v285.js')<loader.indexOf('kanken9-exam-v283.js'));
assert.ok(loader.indexOf('kanken9-exam-finalize-v283.js')<loader.indexOf('kanken9-quality-v285.js'));
assert.ok(loader.includes('kanken9-paper-layout-v285.css?v=2850'));
const releaseAsset=html.match(/app-v240-release\.js\?v=(\d+)/);
assert.ok(releaseAsset&&Number(releaseAsset[1])>=2850,'Current or newer release must refresh iPad loader');
assert.ok(html.includes('id="okuriPrompt"')&&html.includes('id="strokeMsg"'),'Keep school DOM hooks');
console.log('PASS v2.8.5: 105 / 150 original items, mixed on/kun, grade-2 strokes, actual same-component VI, 25 answer-safe writing items and side-by-side vertical Pencil paper.');
